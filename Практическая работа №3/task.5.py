# Задание 5. Работа с коллекциями

# создание списка продуктов
shopping_list = ["Сухарики", "Чипсы", "Яблоки", "Сок"]

# вывод исходного списка
print("Исходный список продуктов:")
print(shopping_list)

# добавление нового продукта
shopping_list.append("Клубника")


# вывод измененного списка
print("\nСписок после добавления продукта:")
print(shopping_list)

# создание множества из списка
unique_items = set(shopping_list)

# вывод множества
print("\nМножество продуктов:")
print(unique_items)

# сравнение списка и множества
print("\nКоличество элементов в списке:", len(shopping_list))
print("Количество элементов в множестве:", len(unique_items))