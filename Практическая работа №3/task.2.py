# Задание 2. Изменяемость и неизменяемость

# создание списка
my_list = [1, 2, 3]

print("Исходный список:", my_list)

# изменение первого элемента списка
my_list[0] = 100

print("Измененный список:", my_list)


# создание кортежа
my_tuple = (1, 2, 3)

print("\nИсходный кортеж:", my_tuple)

# попытка изменить первый элемент кортежа
try:
    my_tuple[0] = 100
except TypeError:
    print("Ошибка: кортеж нельзя изменять.")


# создание строки
my_string = "cat"

print("\nИсходная строка:", my_string)

# попытка изменить первый символ строки
try:
    my_string[0] = "b"
except TypeError:
    print("Ошибка: строку нельзя изменять.")
