# Задача 3. Шахматная доска

# ввод координат первой клетки
print("Введите координаты первой клетки:")
x1, y1 = map(int, input().split())

# ввод координат второй клетки
print("Введите координаты второй клетки:")
x2, y2 = map(int, input().split())

# проверка правильности координат
if not (1 <= x1 <= 8 and 1 <= y1 <= 8
        and 1 <= x2 <= 8 and 1 <= y2 <= 8):
    print("Ошибка ввода")

# проверка цвета клеток
elif (x1 + y1) % 2 == (x2 + y2) % 2:
    print("YES")
else:
    print("NO")