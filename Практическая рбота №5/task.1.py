# Задача 1. Калькулятор налогов

# налоговая ставка
TAX_RATE = 0.13

# ввод годового дохода
income = float(input("Введите ваш годовой доход: "))

# расчет налога
tax = income * TAX_RATE

# расчет дохода после вычета налога
income_after_tax = income - tax

# вывод результатов
print(f"Общая сумма дохода: {income:,.2f} руб.")
print(f"Сумма налога: {tax:,.2f} руб.")
print(f"Доход после вычета налога: {income_after_tax:,.2f} руб.")