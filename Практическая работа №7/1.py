
rating = int(input("введите рейтинг продукта от 1 до 10: "))

match rating:  # проверяет значение переменной rating
    case 9 | 10:
        print(f"отличный продукт! 🌟настоятельно рекомендую!")

    case 7 | 8:
        print(f"хороший продукт! 😊рекомендую!")

    case 4 | 5 | 6:
        print(f"средний продукт! 😐можно попробовать.")

    case 1 | 2 | 3:
        print(f"плохой продукт! ❌не рекомендую.")

    case _:
        print(f"ошибка!введите число от 1 до 10.")
